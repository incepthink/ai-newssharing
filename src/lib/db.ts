const TABLES = `
CREATE TABLE IF NOT EXISTS articles (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category      TEXT NOT NULL DEFAULT 'general',
  raw_text      TEXT NOT NULL,
  title         TEXT NOT NULL DEFAULT '',
  body          TEXT NOT NULL DEFAULT '',
  district      TEXT,
  language      TEXT NOT NULL DEFAULT 'mr',
  release_no    TEXT,
  office        TEXT,
  department    TEXT,
  attribution   TEXT,
  bullets       TEXT NOT NULL DEFAULT '[]',
  dateline      TEXT,
  byline        TEXT,
  status        TEXT NOT NULL DEFAULT 'pending',
  submitted_by  TEXT NOT NULL DEFAULT 'dlo',
  submitted_at  TEXT NOT NULL,
  approved_at   TEXT,
  fold_date     TEXT NOT NULL,
  poster_url    TEXT,
  source_url    TEXT
);

CREATE TABLE IF NOT EXISTS folds (
  "date"        TEXT PRIMARY KEY,
  article_order TEXT NOT NULL DEFAULT '[]',
  finalized_at  TEXT
);
`

/**
 * CREATE TABLE IF NOT EXISTS never adds a column to a table that already exists,
 * so columns introduced after someone's database was created need this.
 */
const MIGRATIONS = `
ALTER TABLE articles ADD COLUMN IF NOT EXISTS byline     TEXT;
ALTER TABLE articles ADD COLUMN IF NOT EXISTS category   TEXT NOT NULL DEFAULT 'general';
ALTER TABLE articles ADD COLUMN IF NOT EXISTS poster_url TEXT;
ALTER TABLE articles ADD COLUMN IF NOT EXISTS source_url TEXT;
`

const INDEXES = `
CREATE INDEX IF NOT EXISTS idx_articles_fold   ON articles(fold_date, status);
CREATE INDEX IF NOT EXISTS idx_articles_dist   ON articles(district, status);
CREATE INDEX IF NOT EXISTS idx_articles_cat    ON articles(category, fold_date);
CREATE INDEX IF NOT EXISTS idx_articles_source ON articles(source_url);
`

/**
 * Runs once per process. Two instances cold-starting together can race inside
 * IF NOT EXISTS and one loses with a duplicate-object error; that means the
 * other created it, so it is safe to swallow.
 */
export function ensureSchema(): Promise<void> {
  globalForPg._schema ??= (async () => {
    let client: PoolClient | undefined
    try {
      client = await pool().connect()
      // Must run before the indexes: an index over a column that MIGRATIONS has
      // not added yet fails outright, and that failure takes every route with it.
      for (const batch of [TABLES, MIGRATIONS, INDEXES]) {
        try {
          await client.query(batch)
        } catch (err) {
          if (!isDuplicateObject(err)) throw err
        }
      }
    } catch (err) {
      globalForPg._schema = undefined // let the next request retry
      throw err
    } finally {
      client?.release()
    }
  })()
  return globalForPg._schema
}

function isDuplicateObject(err: unknown): boolean {
  const code = (err as { code?: string })?.code
  return code === '23505' || code === '42P07' || code === '42701'
}

/* ---------------------------------------------------------------- mapping */

function toArticle(r: Row): Article {
  return {
    id: Number(r.id),
    category: (r.category as Category) ?? 'general',
    raw_text: r.raw_text as string,
    title: r.title as string,
    body: r.body as string,
    district: (r.district as string) ?? null,
    language: r.language as Language,
    release_no: (r.release_no as string) ?? null,
    office: (r.office as string) ?? null,
    department: (r.department as string) ?? null,
    attribution: (r.attribution as string) ?? null,
    bullets: JSON.parse((r.bullets as string) || '[]'),
    dateline: (r.dateline as string) ?? null,
    byline: (r.byline as string) ?? null,
    status: r.status as Status,
    submitted_by: r.submitted_by as string,
    submitted_at: r.submitted_at as string,
    approved_at: (r.approved_at as string) ?? null,
    fold_date: r.fold_date as string,
    poster_url: (r.poster_url as string) ?? null,
    source_url: (r.source_url as string) ?? null,
  }
}

