export interface CreateArticleInput {
  category?: Category
  raw_text: string
  title?: string
  body?: string
  district?: string | null
  language?: Language
  release_no?: string | null
  office?: string | null
  department?: string | null
  attribution?: string | null
  bullets?: string[]
  dateline?: string | null
  byline?: string | null
  status?: Status
  submitted_by?: string
  submitted_at?: string
  approved_at?: string | null
  fold_date: string
  poster_url?: string | null
  source_url?: string | null
}

export async function createArticle(input: CreateArticleInput): Promise<Article> {
  const row = await one(
    `INSERT INTO articles
      (category, raw_text, title, body, district, language, release_no, office, department,
       attribution, bullets, dateline, byline, status, submitted_by, submitted_at, approved_at, fold_date,
       poster_url, source_url)
     VALUES
      (@category, @raw_text, @title, @body, @district, @language, @release_no, @office, @department,
       @attribution, @bullets, @dateline, @byline, @status, @submitted_by, @submitted_at, @approved_at, @fold_date,
       @poster_url, @source_url)
     RETURNING *`,
    {
      category: input.category ?? 'general',
      raw_text: input.raw_text,
      title: input.title ?? '',
      body: input.body ?? input.raw_text,
      district: input.district ?? null,
      language: input.language ?? 'mr',
      release_no: input.release_no ?? null,
      office: input.office ?? null,
      department: input.department ?? null,
      attribution: input.attribution ?? null,
      bullets: JSON.stringify(input.bullets ?? []),
      dateline: input.dateline ?? null,
      byline: input.byline ?? null,
      status: input.status ?? 'pending',
      submitted_by: input.submitted_by ?? 'dlo',
      submitted_at: input.submitted_at ?? new Date().toISOString(),
      approved_at: input.approved_at ?? (input.status === 'approved' ? new Date().toISOString() : null),
      fold_date: input.fold_date,
      poster_url: input.poster_url ?? null,
      source_url: input.source_url ?? null,
    },
  )
  return toArticle(row!)
}

export async function getArticle(id: number): Promise<Article | null> {
  const r = await one('SELECT * FROM articles WHERE id = @id', { id })
  return r ? toArticle(r) : null
}

export async function getArticleBySourceUrl(sourceUrl: string): Promise<Article | null> {
  const r = await one('SELECT * FROM articles WHERE source_url = @sourceUrl', { sourceUrl })
  return r ? toArticle(r) : null
}

export interface ListFilter {
  fold_date?: string
  status?: Status
  category?: Category
  district?: string
  language?: Language
  from?: string
  to?: string
}

export async function listArticles(f: ListFilter = {}): Promise<Article[]> {
  const where: string[] = []
  const params: Record<string, unknown> = {}
  if (f.fold_date) { where.push('fold_date = @fold_date'); params.fold_date = f.fold_date }
  if (f.status) { where.push('status = @status'); params.status = f.status }
  if (f.category) { where.push('category = @category'); params.category = f.category }
  if (f.district) { where.push('district = @district'); params.district = f.district }
  if (f.language) { where.push('language = @language'); params.language = f.language }
  if (f.from) { where.push('fold_date >= @from'); params.from = f.from }
  if (f.to) { where.push('fold_date <= @to'); params.to = f.to }
  const sql =
    'SELECT * FROM articles' +
    (where.length ? ` WHERE ${where.join(' AND ')}` : '') +
    ' ORDER BY id DESC'
  return (await all(sql, params)).map(toArticle)
}

const UPDATABLE = [
  'title', 'body', 'district', 'language', 'release_no', 'office', 'department',
  'attribution', 'dateline', 'byline', 'status', 'category', 'poster_url', 'source_url',
] as const

export async function updateArticle(id: number, patch: Partial<Article>): Promise<Article | null> {
  const sets: string[] = []
  const params: Record<string, unknown> = { id }

  for (const k of UPDATABLE) {
    if (k in patch) { sets.push(`${k} = @${k}`); params[k] = (patch as Record<string, unknown>)[k] ?? null }
  }
  if ('bullets' in patch) { sets.push('bullets = @bullets'); params.bullets = JSON.stringify(patch.bullets ?? []) }
  if (patch.status === 'approved') { sets.push('approved_at = @approved_at'); params.approved_at = new Date().toISOString() }
  if (!sets.length) return getArticle(id)

  await run(`UPDATE articles SET ${sets.join(', ')} WHERE id = @id`, params)
  return getArticle(id)
}

export async function deleteArticle(id: number): Promise<void> {
  await run('DELETE FROM articles WHERE id = @id', { id })
}

/**
 * Suggest the next वृत्त क्र. The desk can always override — DGIPR's counter
 * advances outside this system too, so this is a convenience, not a source of truth.
 *
 * Only all-digit release numbers are considered: Postgres, unlike SQLite, raises
 * on a CAST of '12अ' to integer rather than quietly reading the leading digits.
 */
export async function suggestReleaseNo(): Promise<string> {
  const r = await one(
    `SELECT release_no FROM articles
     WHERE release_no ~ '^[0-9]+$'
     ORDER BY CAST(release_no AS INTEGER) DESC LIMIT 1`,
  )
  const last = r ? Number(r.release_no) : 0
  return String(last + 1)
}

/* ------------------------------------------------------------------ folds */

export async function getFold(date: string): Promise<Fold> {
  const r = await one('SELECT * FROM folds WHERE "date" = @date', { date })
  const approved = await listArticles({ fold_date: date, status: 'approved' })
  const stored: number[] = r ? JSON.parse(r.article_order as string) : []
  const live = new Set(approved.map((a) => a.id))

  // Keep the desk's hand-ordering, drop anything no longer approved, and
  // append newly approved articles at the end. There is no cutoff, so this
  // has to stay correct when an article is approved late.
  const order = stored.filter((id) => live.has(id))
  for (const a of approved) if (!order.includes(a.id)) order.push(a.id)

  return { date, article_order: order, finalized_at: (r?.finalized_at as string) ?? null }
}

export async function setFoldOrder(date: string, order: number[]): Promise<Fold> {
  await run(
    `INSERT INTO folds ("date", article_order) VALUES (@date, @order)
     ON CONFLICT ("date") DO UPDATE SET article_order = EXCLUDED.article_order`,
    { date, order: JSON.stringify(order) },
  )
  return getFold(date)
}

/** Approved articles for a date, in the desk's chosen order. */
export async function foldArticles(date: string): Promise<Article[]> {
  const fold = await getFold(date)
  const approved = await listArticles({ fold_date: date, status: 'approved' })
  const byId = new Map(approved.map((a) => [a.id, a]))
  return fold.article_order.map((id) => byId.get(id)).filter((a): a is Article => !!a)
}

/* ------------------------------------------------------------------ stats */

export interface DistrictCount { district: string; count: number }

export async function districtCounts(from: string, to: string): Promise<DistrictCount[]> {
  const rows = await all(
    `SELECT district, COUNT(*) AS count
     FROM articles
     WHERE status = 'approved' AND district IS NOT NULL
       AND fold_date >= @from AND fold_date <= @to
     GROUP BY district`,
    { from, to },
  )
  // COUNT(*) is a bigint, which pg hands back as a string.
  return rows.map((r) => ({ district: r.district as string, count: Number(r.count) }))
}

/** Daily totals across the range — drives the time slider. */
export async function dailyCounts(from: string, to: string): Promise<{ date: string; count: number }[]> {
  const rows = await all(
    `SELECT fold_date AS date, COUNT(*) AS count
     FROM articles
     WHERE status = 'approved' AND fold_date >= @from AND fold_date <= @to
     GROUP BY fold_date ORDER BY fold_date`,
    { from, to },
  )
  return rows.map((r) => ({ date: r.date as string, count: Number(r.count) }))
}
