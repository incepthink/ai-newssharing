import { Pool, type PoolClient } from 'pg'
import type { Article, Category, Fold, Language, Status } from './types'

/**
 * Serverless functions get one pool per warm instance, and RDS counts every one
 * of those against max_connections. Keep the pool small and let idle connections
 * go quickly, so a burst of instances doesn't exhaust the server.
 */
function makePool(): Pool {
  const connectionString = process.env.DATABASE_URL
  if (!connectionString) {
    throw new Error('DATABASE_URL is not set — point it at your Postgres/RDS instance.')
  }
  return new Pool({
    connectionString,
    max: Number(process.env.PG_POOL_MAX ?? 3),
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 10_000,
    ssl: sslConfig(),
  })
}

/**
 * RDS terminates TLS with an Amazon-issued cert that isn't in Node's trust store.
 * Supply the RDS CA bundle in RDS_CA_CERT to verify it properly; without one we
 * still encrypt but skip verification, which is the common RDS-on-Vercel setup.
 * DATABASE_SSL=disable is for a plaintext local Postgres.
 */
function sslConfig() {
  if (process.env.DATABASE_SSL === 'disable') return undefined
  const ca = process.env.RDS_CA_CERT
  return ca ? { ca, rejectUnauthorized: true } : { rejectUnauthorized: false }
}

// Survives dev hot-reloads, which would otherwise leak a pool per edit.
const globalForPg = globalThis as unknown as { _pool?: Pool; _schema?: Promise<void> }

export function pool(): Pool {
  globalForPg._pool ??= makePool()
  return globalForPg._pool
}

/* ---------------------------------------------------------------- queries */

type Row = Record<string, unknown>

/**
 * Translates the @named placeholders these queries are written with into the
 * positional $1..$n that pg expects. A name repeated in one statement is bound
 * once per occurrence, which is what the callers below rely on.
 */
function bind(sql: string, params: Record<string, unknown>): [string, unknown[]] {
  const values: unknown[] = []
  const text = sql.replace(/@(\w+)/g, (_m, name: string) => {
    values.push(params[name] ?? null)
    return `$${values.length}`
  })
  return [text, values]
}

async function all<T = Row>(sql: string, params: Record<string, unknown> = {}): Promise<T[]> {
  await ensureSchema()
  const [text, values] = bind(sql, params)
  const res = await pool().query(text, values)
  return res.rows as T[]
}

async function one<T = Row>(sql: string, params: Record<string, unknown> = {}): Promise<T | null> {
  const rows = await all<T>(sql, params)
  return rows[0] ?? null
}

async function run(sql: string, params: Record<string, unknown> = {}): Promise<void> {
  await all(sql, params)
}

